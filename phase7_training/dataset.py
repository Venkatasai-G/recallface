from __future__ import annotations

from pathlib import Path
from typing import Any

import torch
from torch.utils.data import Dataset


class NavigationTransitionDataset(Dataset):
    """
    Build Phase 7 training transitions from Phase 6 session files.

    Each transition corresponds to:

        previous selected latent
            ->
        current round candidate set
            ->
        observed selected latent

    Round 1 is excluded because it is generated by the fixed
    Phase 2 starter set and does not use Projector/Sampler.
    """

    def __init__(
        self,
        session_files: list[Path],
        expected_candidates: int = 12,
        expected_rounds: int = 20,
    ) -> None:
        self.session_files = list(session_files)
        self.expected_candidates = expected_candidates
        self.expected_rounds = expected_rounds

        if not self.session_files:
            raise ValueError("No session files were provided.")

        self.transitions: list[dict[str, Any]] = []

        self._build_index()

    def _load_session(self, path: Path) -> dict[str, Any]:
        data = torch.load(
            path,
            map_location="cpu",
            weights_only=False,
        )

        if "session_id" not in data:
            raise ValueError(f"{path.name}: missing session_id")

        if "target_latent" not in data:
            raise ValueError(f"{path.name}: missing target_latent")

        if "rounds" not in data:
            raise ValueError(f"{path.name}: missing rounds")

        return data

    def _build_index(self) -> None:
        for path in self.session_files:
            data = self._load_session(path)

            target = data["target_latent"].float()
            rounds = data["rounds"]

            if target.shape != (512,):
                raise ValueError(
                    f"{path.name}: target_latent must be (512,), "
                    f"got {tuple(target.shape)}"
                )

            if len(rounds) != self.expected_rounds:
                raise ValueError(
                    f"{path.name}: expected "
                    f"{self.expected_rounds} rounds, "
                    f"got {len(rounds)}"
                )

            # R1 -> R2 ... R19 -> R20
            for round_idx in range(1, self.expected_rounds):
                previous_round = rounds[round_idx - 1]
                current_round = rounds[round_idx]

                previous_candidates = (
                    previous_round["candidate_latents"]
                ).float()

                current_candidates = (
                    current_round["candidate_latents"]
                ).float()

                current_scores = (
                    current_round["similarity_scores"]
                ).float()

                previous_selected = int(
                    previous_round["selected_index"]
                )

                current_selected = int(
                    current_round["selected_index"]
                )

                previous_state = previous_candidates[
                    previous_selected
                ]

                selected_next = current_candidates[
                    current_selected
                ]

                if previous_candidates.shape != (
                    self.expected_candidates,
                    512,
                ):
                    raise ValueError(
                        f"{path.name}: R{round_idx} candidate shape "
                        f"is {tuple(previous_candidates.shape)}"
                    )

                if current_candidates.shape != (
                    self.expected_candidates,
                    512,
                ):
                    raise ValueError(
                        f"{path.name}: R{round_idx + 1} candidate shape "
                        f"is {tuple(current_candidates.shape)}"
                    )

                if current_scores.shape != (
                    self.expected_candidates,
                ):
                    raise ValueError(
                        f"{path.name}: R{round_idx + 1} score shape "
                        f"is {tuple(current_scores.shape)}"
                    )

                transition = {
                    "session_id": int(data["session_id"]),
                    "round_number": int(
                        current_round["round_number"]
                    ),
                    "current_latent": previous_state,
                    "target_latent": target,
                    "candidate_latents": current_candidates,
                    "similarity_scores": current_scores,
                    "selected_index": current_selected,
                    "selected_latent": selected_next,
                    "confidence": float(
                        current_round.get("confidence", 1.0)
                    ),
                }

                self.transitions.append(transition)

    def __len__(self) -> int:
        return len(self.transitions)

    def __getitem__(self, index: int) -> dict[str, Any]:
        item = self.transitions[index]

        current_latent = item["current_latent"]
        selected_latent = item["selected_latent"]

        # Observed movement produced by the Phase 6 system.
        target_direction = (
            selected_latent - current_latent
        )

        return {
            "session_id": item["session_id"],
            "round_number": item["round_number"],
            "current_latent": current_latent.clone(),
            "target_latent": item["target_latent"].clone(),
            "candidate_latents": item["candidate_latents"].clone(),
            "similarity_scores": item["similarity_scores"].clone(),
            "selected_index": item["selected_index"],
            "selected_latent": selected_latent.clone(),
            "target_direction": target_direction.clone(),
            "confidence": item["confidence"],
        }